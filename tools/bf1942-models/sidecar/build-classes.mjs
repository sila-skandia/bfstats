// Build classes.json from the class-map doc's object table.
//
// features/udp-sidecar/decodes/class-map.md is the account (it carries the
// evidence for every link); this turns its "observed objects" table into data
// the decoders and the coverage report can read, so the class of an object is
// looked up rather than guessed from a body length.
//
//   node sidecar/build-classes.mjs [class-map.md] [classes.json]
//
// The table's columns are: netId | tid | template | object class |
// networkable class | setNetUpdate | records | bits avg. A netId cell may list
// several ids for one template ("4, 510, 512"), and a template may appear in
// several rows (its objects were created at different times), so the map is
// built per netId and per tid, both keyed by the template name.

import fs from 'node:fs';
import path from 'node:path';

const docPath = process.argv[2] ?? path.join('..', '..', 'features', 'udp-sidecar', 'decodes', 'class-map.md');
const outPath = process.argv[3] ?? path.join('sidecar', 'classes.json');

const text = fs.readFileSync(docPath, 'utf8');
const strip = (s) => s.replace(/`/g, '').replace(/\s*\[PCO\]\s*/g, '').trim();

const byNetId = {};
const byTid = {};
const byTemplate = {};
let rows = 0;

for (const line of text.split('\n')) {
  if (!line.startsWith('|') || /^\|\s*-+/.test(line) || line.includes('netId | tid')) continue;
  const c = line.split('|').map((s) => s.trim());
  if (c.length < 9) continue;
  const ids = c[1].split(',').map((s) => s.trim()).filter((s) => /^\d+$/.test(s));
  const tid = Number(c[2]);
  const tmpl = strip(c[3]);
  const objectClass = strip(c[4]);
  const networkableClass = strip(c[5]);
  const setNetUpdate = strip(c[6]);
  if (!ids.length || !tmpl || !networkableClass) continue;
  rows++;
  const entry = { tid, tmpl, objectClass, networkableClass, setNetUpdate };
  for (const id of ids) byNetId[id] = entry;
  if (Number.isFinite(tid)) byTid[tid] = entry;
  // A template's class is the same wherever it appears; keep the first.
  byTemplate[tmpl] ??= entry;
}

const out = {
  // Generated by sidecar/build-classes.mjs from the class-map doc's table.
  // The doc is the account; this is the same mapping as data.
  source: 'features/udp-sidecar/decodes/class-map.md',
  byNetId,
  byTid,
  byTemplate,
};
fs.writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n');
console.log(`${rows} rows -> ${Object.keys(byNetId).length} netIds, ${Object.keys(byTid).length} tids, ${Object.keys(byTemplate).length} templates -> ${outPath}`);
