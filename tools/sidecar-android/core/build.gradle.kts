tasks.withType<Test>().configureEach {
  System.getenv("SIDECAR_PARITY_REBUILD")?.let { environment("SIDECAR_PARITY_REBUILD", it) }
}
tasks.withType<KotlinNativeTest>().configureEach {
  System.getenv("SIDECAR_PARITY_REBUILD")?.let { environment("SIDECAR_PARITY_REBUILD", it) }
}
