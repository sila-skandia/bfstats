#!/usr/bin/env python3
"""Write the proxy WINMM.dll's export stubs (winmm_exports.S) and its .def.

The server finds WINMM.dll in its own folder before the system's, so the
recorder loads as that dll. Every module in the process that imports WINMM
then binds to it: the server itself (timeGetTime) and any system dll loaded
later. A name it does not export stops that module from loading, and on real
Windows that stops the server from starting. So it exports every winmm
function, each a jump through a table entry that is filled on the first
call from the system's own winmm.dll (target_w32ded.c, w32_winmm_resolve).

Usage: winmm_exports.py <outdir>
"""
import sys
from pathlib import Path

# Wine 11's winmm exports, which follow Windows', plus the few Windows-only
# ones. A name the system dll lacks resolves to a stub that returns 0.
