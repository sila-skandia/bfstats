def main() -> None:
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    names = sorted(set(NAMES))
    s = [
        "/* Generated by winmm_exports.py: one stub a winmm export. */",
        ".text",
    ]
    for i, n in enumerate(names):
        s += [f".globl _w32p_{n}", f"_w32p_{n}:", f"  jmp *_w32p_table+{4 * i}"]
    for i, _ in enumerate(names):
        s += [f"_w32p_res_{i}:", f"  pushl ${i}", "  jmp _w32p_resolve_common"]
    # The first call of a stub lands here with its index on the stack above
    # the caller's return address: resolve it, then return into the real
    # function with the stack as the caller left it.
    s += [
        "_w32p_resolve_common:",
        "  pushal",
        "  pushfl",
        "  pushl 36(%esp)",
        "  call _w32_winmm_resolve",
        "  addl $4, %esp",
        "  movl %eax, 36(%esp)",
        "  popfl",
        "  popal",
        "  ret",
        ".data",
        ".align 4",
        ".globl _w32p_table",
        "_w32p_table:",
    ]
    s += [f"  .long _w32p_res_{i}" for i, _ in enumerate(names)]
    s += [".section .rdata", ".align 4", ".globl _w32p_names", "_w32p_names:"]
    s += [f"  .long _w32p_name_{i}" for i, _ in enumerate(names)]
    s += [".globl _w32p_count", "_w32p_count:", f"  .long {len(names)}"]
    for i, n in enumerate(names):
        s += [f"_w32p_name_{i}:", f'  .asciz "{n}"']
    (out / "winmm_exports.S").write_text("\n".join(s) + "\n")
    d = ["LIBRARY WINMM.dll", "EXPORTS"] + [f"  {n} = w32p_{n}" for n in names]
    (out / "winmm.def").write_text("\n".join(d) + "\n")


if __name__ == "__main__":
    main()
